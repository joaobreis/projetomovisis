const existentes = (await m.listServerFunctionsMitra({ projectId })).result || [];
const ids = {};
async function salvar(f, type = 'SQL') {
  const ex = existentes.find(x => x.name === f.name);
  if (ex) { await m.updateServerFunctionMitra({ projectId, serverFunctionId: ex.id, code: f.code, description: f.description }); ids[f.name] = ex.id; }
  else { const r = await m.createServerFunctionMitra({ projectId, name: f.name, type, code: f.code, description: f.description }); ids[f.name] = r.result.serverFunctionId; }
}
for (const f of funcoes) await salvar(f);

